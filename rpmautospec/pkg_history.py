def _checkout_tree_files(
    commit: pygit2.Commit, tree: pygit2.Tree, topdir: Path, reldir: PurePath = PurePath(".")
) -> None:
    """Check out files, but don’t manipulate git status.

    :param commit:  The GIT commit being processed.
    :param tree:    The (sub)tree to check out files for.
    :param topdir:  The top directory for the contents to be checked out.
    :param reldir:  The relative directory being processed.
    """
    curdir = topdir / reldir
    curdir.mkdir(parents=True, exist_ok=True)
    for entry in tree:
        relpath = reldir / entry.name
        if isinstance(entry, pygit2.Tree):
            _checkout_tree_files(commit, entry, topdir, relpath)
        else:  # isinstance(entry, pygit2.Blob)
            fpath = curdir / entry.name
            if stat.S_ISLNK(entry.filemode):
                fpath.symlink_to(entry.data)
            else:  # stat.S_ISREG(entry.filemode)
                with BlobIO(entry, as_path=str(relpath), commit_id=commit.id) as f:
                    fpath.write_bytes(f.read())
                fpath.chmod(stat.S_IMODE(entry.filemode))


CHANGELOG_MODES = ("walk", "accumulated", "tagged-only", "mixed-accumulated", "mixed-tagged-only")
TAG_CHANGELOG_MODES = tuple(mode for mode in CHANGELOG_MODES if mode != "walk")
CHANGELOG_DUPLICATES = ("lowest", "highest")


def _base_release(verflags: dict) -> int:
    """Get the base release (``%autorelease -b N``) from pre-computed verflags.

    :param verflags: pre-computed verflags dict from spec parsing
    :return: the base release, 1 if the spec doesn't set one
    """
    return int(verflags["base"]) if verflags.get("base") is not None else 1


class PkgHistoryProcessor:
    autorelease_flags_re = re.compile(
        r"""^(?P<prefix>.*)
        E(?P<extraver>[^_]*)
        _S(?P<snapinfo>[^_]*)
        _P(?P<prerelease>[01])
        _B(?P<base>\d*)
        (?P<suffix>.*)$""",
        re.VERBOSE,
    )

    specparser: "SpecParser"

    def __init__(self, spec_or_path: Union[str, Path]):
        self.specparser = AutoSpecParser()

        if isinstance(spec_or_path, str):
            spec_or_path = Path(spec_or_path)

        spec_or_path = spec_or_path.absolute()

        if not spec_or_path.exists():
            raise FileNotFoundError(f"Spec file or path '{spec_or_path}' doesn't exist.")
        elif spec_or_path.is_dir():
            self.path = spec_or_path
            self.name = spec_or_path.name
            self.specfile = spec_or_path / f"{self.name}.spec"
        elif spec_or_path.is_file():
            if spec_or_path.suffix != ".spec":
                raise ValueError(
                    "File specified as `spec_or_path` must have '.spec' as an extension."
                )
            self.path = spec_or_path.parent
            self.name = spec_or_path.stem
            self.specfile = spec_or_path
        else:
            raise SpecialFileError("File specified as `spec_or_path` is not a regular file.")

        if not self.specfile.exists():
            raise FileNotFoundError(f"Spec file '{self.specfile}' doesn't exist in '{self.path}'.")

        try:
            self.repo = pygit2.Repository(
                self.path, flags=pygit2.enums.RepositoryOpenFlag.NO_SEARCH
            )
        except pygit2.GitError:
            self.repo = None

        self._rpmverflags_for_commits = {}
        self._tags_by_namespace: dict[str, dict[str, list[NVR]]] = {}
        # Map of mixed-mode terminator commits -> release number
        # (see _run_mixed())
        self._stop_commits: dict[str, int] = {}

    def get_tags_for_namespace(self, namespace: str) -> dict:
        """Get all git tags under the namespace and parse their N-V-Rs.

        Only tags with numeric release values are included, non-numerics would
        not have been generated by autorelease and e.g. packagers working with
        release candidate builds.

        Results are cached per namespace.

        :param namespace: the git tag namespace to filter on
        :return: dict mapping commit hex sha to list of NVR namedtuples
        """
        if namespace in self._tags_by_namespace:
            return self._tags_by_namespace[namespace]

        if not self.repo:
            self._tags_by_namespace[namespace] = {}
            return {}

        result = {}
        tag_ref_namespace = f"refs/tags/{namespace}/"
        for ref_name in self.repo.references:
            if not ref_name.startswith(tag_ref_namespace):
                continue
            tag_name = ref_name[len("refs/tags/") :]
            try:
                parsed = parse_namespaced_nvr(tag_name, namespace)
            except ValueError:
                continue
            if parsed.name != self.name:
                continue
            # Strip any suffixing and ensure the first part is just a number
            release = parsed.release.split(".", 1)[0]
            if not release.isdigit():
                continue
            parsed = parsed._replace(release=release)
            ref = self.repo.references[ref_name]
            commit_id = str(ref.peel(pygit2.Commit).id)
            result.setdefault(commit_id, []).append(parsed)

        self._tags_by_namespace[namespace] = result
        return result

    def _get_changelog_flags(self) -> dict[str, Optional[str]]:
        """Get the ``-m`` and ``-d`` options of ``%autochangelog`` from the spec file.

        ``-m`` takes one of CHANGELOG_MODES, ``-d`` lowest or highest.

        The first line that rpmautospec_core recognizes as ``%autochangelog`` is looked at, bare
        (``%autochangelog -m x``) or braced (``%{autochangelog -m x}``). ``%{?autochangelog}`` takes
        none, as rpm drops arguments given in that form.

        :return: dict with the keys ``mode`` and ``duplicate``, None for options not set
        :raises SpecParseFailure: if an option or its value is unknown, or options are given to
            ``%{?autochangelog}``
        """
        flags = {"mode": None, "duplicate": None}
        if not self.specfile.exists():
            return flags

        # The line is the one rpmautospec_core found, counted the way it reads the file.
        lineno = check_specfile_features(self.specfile, enable_caching=False).autochangelog_lineno
        if lineno is None:
            return flags
        line = self.specfile.read_text(encoding="utf-8", errors="surrogateescape").split("\n")[
            lineno - 1
        ]
        match = autochangelog_re.match(line)

        macro = match.group().lstrip()
        if macro.startswith("%{"):
            conditional = macro.startswith("%{?")
            rest = macro[:-1].split("autochangelog", 1)[1]
        else:
            conditional = False
            rest = line[match.end() :]
        words = rest.split() if rest[:1].isspace() else []
        if conditional and words:
            raise SpecParseFailure(
                "Options are ignored by rpm in %{?autochangelog ...}, use %autochangelog or "
                "%{autochangelog ...}",
                code="changelog-option-invalid",
            )

        args = iter(words)
        for arg in args:
            if arg == "--":
                break
            if len(arg) < 2 or arg[0] != "-":
                continue
            option, value = arg[:2], arg[2:] or next(args, "")
            if option == "-m":
                key, allowed = "mode", CHANGELOG_MODES
            elif option == "-d":
                key, allowed = "duplicate", CHANGELOG_DUPLICATES
            else:
                raise SpecParseFailure(
                    f"Unknown option {arg!r} to %autochangelog, allowed are -m and -d",
                    code="changelog-option-invalid",
                )
            if value not in allowed:
                raise SpecParseFailure(
                    f"Invalid value {value!r} for {option} of %autochangelog, allowed are: "
                    + ", ".join(allowed),
                    code="changelog-option-invalid",
                )
            flags[key] = value

        return flags

    @staticmethod
    def _resolve_changelog_options(
        flags: dict[str, Optional[str]],
        git_tag_namespace: Optional[str],
        changelog_mode: Optional[str],
        changelog_use_highest_release_tag: Optional[bool],
    ) -> tuple[str, bool]:
        """Decide how the release and changelog get generated.

        Options in the spec file override CLI arguments.

        Without a git tag namespace there are no tags to work with so the history is
        walked. A spec file that asks for tags is an error, CLI calls that do are
        ignored with a warning.

        :param flags: the options from the spec file, see _get_changelog_flags()
        :param git_tag_namespace: the namespace to filter git tags on, if any
        :param changelog_mode: one of CHANGELOG_MODES, None for the default
            (accumulated with a git tag namespace, walk otherwise)
        :param changelog_use_highest_release_tag: pick highest vs lowest release per commit
        :return: the mode (one of CHANGELOG_MODES) and whether to use the highest
            release tag per commit
        :raises SpecParseFailure: if the spec file asks for tags without a git tag namespace
        :raises ValueError: if changelog_mode is unknown
        """
        if changelog_mode not in (None, *CHANGELOG_MODES):
            raise ValueError(
                f"Unknown changelog mode {changelog_mode!r}, allowed are: "
                + ", ".join(CHANGELOG_MODES)
            )

        mode = flags["mode"] or changelog_mode
        if flags["duplicate"]:
            use_highest = flags["duplicate"] == "highest"
        else:
            use_highest = bool(changelog_use_highest_release_tag)

        if not git_tag_namespace:
            # Walk can process w/o tag namespace; all tag modes need one
            if mode in TAG_CHANGELOG_MODES:
                if flags["mode"]:
                    raise SpecParseFailure(
                        f"%autochangelog -m {mode} needs a git tag namespace",
                        code="changelog-mode-without-namespace",
                    )
                log.warning(
                    "Changelog mode %s needs a git tag namespace, walking the history", mode
                )
            if use_highest:
                if flags["duplicate"]:
                    raise SpecParseFailure(
                        "%autochangelog -d highest needs a git tag namespace",
                        code="changelog-duplicate-without-namespace",
                    )
                log.warning("The highest release tag needs a git tag namespace, ignoring it")
            mode, use_highest = "walk", False
        elif mode is None:
            mode = "accumulated"

        return mode, use_highest

    @staticmethod
    def _get_rpm_packager() -> str:
        fallback = "John Doe <packager@example.com>"
        try:
            return rpm.expandMacro(f"%{{?packager}}%{{!?packager:{fallback}}}")
        except Exception:
            return fallback

    def _get_rpmverflags(
        self, path: str, name: Optional[str] = None, log_error: bool = True
    ) -> dict[str, Union[str, int]]:
        """Retrieve the epoch/version and %autorelease flags set in spec file."""
        path = Path(path)

        if not name:
            name = path.name

        specfile = path / f"{name}.spec"

        if not specfile.exists():
            log.debug("spec file missing: %s", specfile)
            return {"error": "specfile-missing", "error-detail": "Spec file is missing."}

        with (
            specfile.open(mode="rb") as unabridged,
            NamedTemporaryFile(
                mode="wb", prefix=f"rpmautospec-abridged-{name}-", suffix=".spec"
            ) as abridged,
        ):
            # Attempt to parse a shortened version of the spec file first, to speed up
            # processing in certain cases. This includes all lines before `%prep`, i.e. in most
            # cases everything which is needed to make RPM parsing succeed and contain the info
            # we want to extract.
            for line in unabridged:
                if line.strip() == b"%prep":
                    break
                abridged.write(line)
            abridged.flush()

            candidates = (abridged.name, str(specfile))
            for spec_candidate in candidates:
                try:
                    epoch_version, info = self.specparser.query(path, spec_candidate)
                except SpecParserError as err:
                    error = True
                    if spec_candidate == str(specfile):
                        rpmerr_out = str(err)
                else:
                    error = False
                    rpmerr_out = None
                    break
            else:
                pass  # pragma: no cover
        if error:
            if log_error:
                log.debug("spec file query failed: %s", rpmerr_out)
            return {"error": "specfile-parse-error", "error-detail": rpmerr_out}

        match = self.autorelease_flags_re.search(info)
        if match:
            extraver = match.group("extraver") or None
            snapinfo = match.group("snapinfo") or None
            prerelease = match.group("prerelease") == "1" or None
            base = match.group("base")
            if base:
                base = int(base)
            else:
                base = 1
            # Literal text surrounding the %autorelease flags token in the Release tag value, e.g.:
            #   "3%{?dist}.%{autorelease -n}" -> "3." and ""
            #   "%{autorelease -n}.ABC%{?dist}" -> "" and ".ABC"
            release_prefix = match.group("prefix")
            release_suffix = match.group("suffix")
        else:
            extraver = snapinfo = prerelease = base = None
            release_prefix = release_suffix = ""

        result = {
            "epoch-version": epoch_version,
            "extraver": extraver,
            "snapinfo": snapinfo,
            "prerelease": prerelease,
            "base": base,
            "release-prefix": release_prefix,
            "release-suffix": release_suffix,
        }

        return result

    def _get_rpmverflags_for_commit(self, commit: pygit2.Commit) -> dict[str, Union[str, int]]:
        if commit in self._rpmverflags_for_commits:
            return self._rpmverflags_for_commits[commit]

        with TemporaryDirectory(prefix="rpmautospec-") as workdir:
            workdir = Path(workdir)

            # Only unpack spec file at first.
            try:
                specblob = commit.tree[self.specfile.name]
            except KeyError:
                # no spec file
                error = {"error": "specfile-missing", "error-detail": "Spec file is missing."}
                self._rpmverflags_for_commits[commit] = error
                return error

            specpath = workdir / self.specfile.name
            specpath.write_bytes(specblob.data)

            rpmverflags = self._get_rpmverflags(workdir, self.name, log_error=False)

            if "error" in rpmverflags:
                # Provide all files for %include and %load directives.
                _checkout_tree_files(commit, commit.tree, workdir)
                rpmverflags = self._get_rpmverflags(workdir, self.name)

        self._rpmverflags_for_commits[commit] = rpmverflags
        return rpmverflags

    def release_number_visitor(self, commit: pygit2.Commit, child_info: dict[str, Any]):
        """Visit a commit to determine its release number.

        The coroutine returned first determines if the parent chain(s) must be
        followed, i.e. if one parent has the same package epoch-version,
        suspends execution and yields that to the caller (usually the walk()
        method), who later sends the partial results for this commit (to be
        modified) and full results of parents back (as dictionaries), resuming
        execution to process these and finally yield back the results for this
        commit.
        """
        commit_verflags = verflags = self._get_rpmverflags_for_commit(commit)

        if "error" not in verflags:
            epoch_version = verflags["epoch-version"]
        else:
            epoch_version = None

        if not epoch_version:
            child_must_continue = True
        else:
            epoch_versions_to_check = []
            for p in commit.parents:
                verflags = self._get_rpmverflags_for_commit(p)
                if "error" in verflags:
                    child_must_continue = True
                    break
                epoch_versions_to_check.append(verflags["epoch-version"])
            else:
                child_must_continue = (
                    epoch_version in epoch_versions_to_check or epoch_version is None
                )

        stop_release = self._stop_commits.get(str(commit.id))
        if stop_release is not None:
            # Mixed mode switches behaviors at a tagged commit
            child_must_continue = False

        log.debug("\tepoch_version: %s", epoch_version)
        log.debug("\tchild must continue: %s", child_must_continue)

        # Suspend execution, yield whether caller should continue, and get back the (partial) result
        # for this commit and parent results as dictionaries on resume.
        commit_result, parent_results = yield {"child_must_continue": child_must_continue}

        commit_result["verflags"] = commit_verflags
        commit_result["epoch-version"] = epoch_version
        commit_result["magic-comment-result"] = parse_magic_comments(commit.message)

        log.debug("\tepoch_version: %s", epoch_version)
        log.debug(
            "\tparent rel numbers: %s",
            ", ".join(str(res["release-number"]) if res else "none" for res in parent_results),
        )

        # Find the maximum applicable parent release number and increment by one if the
        # epoch-version can be parsed from the spec file.
        parent_release_numbers = tuple(
            (
                res["release-number"]
                if res
                and (
                    # Paper over gaps in epoch-versions, these could be simple syntax errors in
                    # the spec file, or a retired, then unretired package.
                    epoch_version is None
                    or res["epoch-version"] is None
                    or epoch_version == res["epoch-version"]
                )
                else 0
            )
            for res in parent_results
        )
        release_number = max(parent_release_numbers, default=0)

        if self.specfile.name in commit.tree:
            release_number += 1

        release_number = max(release_number, commit_result["magic-comment-result"].bump_release)

        if stop_release is not None:
            release_number = stop_release

        commit_result["release-number"] = release_number

        log.debug("\trelease_number: %s", release_number)

        commit_result["release-complete"] = self._compose_release(release_number, commit_verflags)

        yield commit_result

    def changelog_visitor(self, commit: pygit2.Commit, child_info: dict[str, Any]):
        """Visit a commit to generate changelog entries for it and its parents.

        It first determines if parent chain(s) must be followed, i.e. if the
        changelog file was modified in this commit and yields that to the
        caller, who later sends the partial results for this commit (to be
        modified) and full results of parents back (as dictionaries), which
        get processed and the results for this commit yielded again.
        """
        child_must_continue = child_info["child_must_continue"]
        # Check if the spec file exists, if not, there will be no changelog.
        specfile_present = f"{self.name}.spec" in commit.tree

        # Find out if the changelog is different from every parent (or present, in the case of the
        # root commit).
        try:
            changelog_blob = commit.tree["changelog"]
        except KeyError:
            changelog_blob = None

        child_changelog_removed = child_info.get("changelog_removed")
        our_changelog_removed = False
        if commit.parents:
            changelog_changed = True
            for parent in commit.parents:
                try:
                    par_changelog_blob = parent.tree["changelog"]
                except KeyError:
                    par_changelog_blob = None
                else:
                    our_changelog_removed = our_changelog_removed or not changelog_blob
                if changelog_blob == par_changelog_blob:
                    changelog_changed = False
        else:
            # With root commits, changelog present means it was changed
            changelog_changed = bool(changelog_blob)

        # Establish which parent to follow (if any, and if we can).
        parent_to_follow = self._parent_to_follow(commit)
        # No parent with the same tree found for a merge: if the changelog is different from all
        # parents, it was updated in the merge commit and we don't care. If it didn't change, we
        # don't know how to continue and need to flag that.
        merge_unresolvable = (
            len(commit.parents) > 1 and parent_to_follow is None and not changelog_changed
        )

        at_stop_commit = str(commit.id) in self._stop_commits
        our_child_must_continue = (
            not (changelog_changed and changelog_blob or merge_unresolvable)
            and child_must_continue
            and not at_stop_commit
        )

        log.debug("\tchangelog changed: %s", changelog_changed)
        log.debug("\tchild changelog removed: %s", child_changelog_removed)
        log.debug("\tour changelog removed: %s", our_changelog_removed)
        log.debug("\tmerge unresolvable: %s", merge_unresolvable)
        log.debug("\tspec file present: %s", specfile_present)
        log.debug("\tchild must continue (incoming): %s", child_must_continue)
        log.debug("\tchild must continue (outgoing): %s", our_child_must_continue)

        commit_result, parent_results = yield {
            "child_must_continue": our_child_must_continue,
            "changelog_removed": not (changelog_blob and changelog_changed)
            and (child_changelog_removed or our_changelog_removed),
        }

        changelog_entry = self._make_changelog_entry(
            commit, commit_result["epoch-version"], commit_result["release-complete"]
        )

        skip_for_changelog = (
            commit_result["magic-comment-result"].skip_changelog or not specfile_present
        )

        if merge_unresolvable:
            log.debug("\tunresolvable merge")
            changelog_entry["error"] = "unresolvable merge"
            previous_changelog = ()
            commit_result["changelog"] = (changelog_entry,)
        elif changelog_changed and changelog_blob:
            log.debug("\tchangelog file changed")
            if not child_changelog_removed:
                changelog_entry["data"] = changelog_blob.data.decode("utf-8", errors="replace")
                commit_result["changelog"] = (changelog_entry,)
            else:
                # The `changelog` file was removed in a later commit, stop changelog generation.
                log.debug("\t  skipping")
                commit_result["changelog"] = ()
        else:
            # Pull previous changelog entries from parent result (if any).
            if len(commit.parents) == 1:
                log.debug("\tone parent: %s", commit.parents[0].short_id)
                previous_changelog = parent_results[0].get("changelog", ())
            else:
                if parent_to_follow:
                    log.debug("\tmultiple parents, follow: %s", parent_to_follow.short_id)
                else:
                    log.debug("\tno parent to follow")
                previous_changelog = ()
                for candidate in parent_results:
                    if not candidate:
                        continue
                    if candidate["commit-id"] == parent_to_follow.id:
                        previous_changelog = candidate.get("changelog", ())
                        skip_for_changelog = True
                        break

            log.debug("\tskip_for_changelog: %s", skip_for_changelog)

            changelog_entry["skip"] = skip_for_changelog

            if not skip_for_changelog:
                commit_result["changelog"] = (changelog_entry,) + previous_changelog
            else:
                commit_result["changelog"] = previous_changelog

        if at_stop_commit:
            # Mixed mode switchover to tagged behaviors
            commit_result["changelog"] = ()

        yield commit_result

    @staticmethod
    def _merge_info(f1: dict[str, Any], f2: dict[str, Any]) -> dict[str, Any]:
        """Merge dicts containing info of previously run visitors."""
        mf = f1.copy()
        for k, v2 in f2.items():
            try:
                v1 = mf[k]
            except KeyError:
                mf[k] = v2
            else:
                if k == "child_must_continue":
                    mf[k] = v1 or v2
                elif k == "changelog_removed":
                    mf[k] = v1 and v2
                else:
                    raise KeyError(f"Unknown information key: {k}")
        return mf

    @contextmanager
    def _stopping_at(self, stop_commits: dict[str, int]) -> Iterator[None]:
        """Make the visitors end the walk at these commits, with the release number given for them.

        :param stop_commits: dict mapping the hex sha of each commit to stop at to its release
        """
        self._stop_commits = stop_commits
        try:
            yield
        finally:
            self._stop_commits = {}

    def _run_on_history(
        self,
        head: pygit2.Commit,
        *,
        visitors: Sequence = (),
        seed_info: Optional[dict[str, Any]] = None,
    ) -> dict[pygit2.Commit, dict[str, Any]]:
        """Process historical commits with visitors and gather results."""
        # This sets the “playing field” for the head commit, it subs for the partial result of a
        # child commit which doesn’t exist.
        seed_info = {"child_must_continue": True} | (seed_info or {})

        # These map visited commits to their (in-flight) visitor coroutines and tracks if they must
        # continue and other auxiliary information.
        commit_coroutines = {}
        commit_coroutines_info = {}

        # This keeps track of the heads of branches that need to be processed.
        branch_heads = [head]
        # This stores the discovered snippets, i.e. linear chains of commits.
        snippets = []

        # Unfortunately, pygit2 only tells us what the parents of a commit are, not what other
        # commits a commit is parent to (its children). Fortunately, Repository.walk() is quick.
        # This maps parent commits to their children.
        commit_children = defaultdict(list)
        for commit in self.repo.walk(head.id):
            for parent in commit.parents:
                commit_children[parent].append(commit)

        ##########################################################################################
        # To process, first walk the tree from the head commit downward, following all branches.
        # Check visitors whether they need parent results to do their work, i.e. the history needs
        # to be processed further, or just traversed.
        #
        # Here, the “top halves” of visitors get merged information from their child commit(s) as
        # well as from visitors that ran prior on the same commit. In practice: during runtime,
        # `changelog_visitor()` gets information from `release_number_visitor()` for the same
        # commit.
        ##########################################################################################

        log.debug("===========================================================")
        log.debug("Extracting linear history snippets from branched history...")
        log.debug("===========================================================")

        # While new branch heads are encountered...
        while branch_heads:
            commit = branch_heads.pop(0)
            snippet = []
            snippets.append(snippet)

            keep_processing = True

            while True:
                if commit in commit_coroutines:
                    # This commit was processed already, so `snippet` can be cut off before it.
                    log.debug("%s: coroutines exist, skipping", commit.short_id)
                    break

                if log.isEnabledFor(logging.DEBUG):
                    log.debug("commit %s: %s", commit.short_id, commit.message.split("\n", 1)[0])

                if commit == head:
                    # Set the stage for the first commit: Visitors expect to get some information
                    # from their child commit(s), as there aren’t any yet, fake it.
                    children_visitors_info = [seed_info for v in visitors]
                else:
                    this_children = commit_children[commit]
                    if not all(child in commit_coroutines for child in this_children):
                        # There's another branch that leads to this parent, put the remainder on the
                        # stack.
                        branch_heads.append(commit)

                        if not snippet:
                            # Don't keep empty snippets on the stack. Unsure if this can be reached.
                            snippets.pop()  # pragma: no cover

                        if log.isEnabledFor(logging.DEBUG):
                            log.debug(
                                "\tunencountered children, putting remainder of snippet aside"
                            )
                            log.debug(
                                "\tmissing children: %s",
                                [
                                    child.short_id
                                    for child in this_children
                                    if child not in commit_coroutines
                                ],
                            )

                        break  # pragma: has-py310

                    # For all visitor coroutines, merge their produced info, e.g. to determine if
                    # any of the children must continue.
                    children_visitors_info = [
                        reduce(
                            lambda info, child: self._merge_info(
                                info, commit_coroutines_info[child][vindex]
                            ),
                            this_children,
                            {},
                        )
                        for vindex, v in enumerate(visitors)
                    ]

                    log.debug(
                        "children_visitors_info[]['child_must_continue']: %s",
                        [info["child_must_continue"] for info in children_visitors_info],
                    )

                    keep_processing = keep_processing and any(  # pragma: no branch
                        info["child_must_continue"] for info in children_visitors_info
                    )

                snippet.append(commit)

                if keep_processing:
                    log.debug("Keep processing: commit %s", commit.id)
                    # Create visitor coroutines for the commit from the functions passed into this
                    # method. Pass the ordered list of "is there a child whose coroutine of the same
                    # visitor wants to continue" into it.
                    commit_coroutines[commit] = coroutines = [
                        v(commit, children_visitors_info[vi]) for vi, v in enumerate(visitors)
                    ]

                    # Consult all visitors for the commit on whether we should continue and store
                    # the results.
                    commit_coroutines_info[commit] = [next(c) for c in coroutines]
                else:
                    # Only traverse this commit. Traversal is important if parent commits are the
                    # root of branches that affect the results (computed release number and
                    # generated changelog).
                    log.debug("Only traversing: commit %s", commit.id)
                    commit_coroutines[commit] = coroutines = None
                    commit_coroutines_info[commit] = [
                        {"child_must_continue": False} for v in visitors
                    ]

                if not commit.parents:
                    log.debug("\tno parents, bailing out")
                    break

                if len(commit.parents) > 1:
                    # merge commit, store new branch head(s) to follow later
                    branch_parents = commit.parents[1:]
                    new_branches = [p for p in branch_parents if p not in commit_coroutines]
                    branch_heads.extend(new_branches)
                    if log.isEnabledFor(logging.DEBUG):
                        log.debug("\tnew branch heads %s", [x.short_id for x in new_branches])
                        log.debug("\tbranch heads: %s", [x.short_id for x in branch_heads])

                # follow (first) parent
                commit = commit.parents[0]
                log.debug("\tparent to follow: %s", commit.short_id)

        ###########################################################################################
        # Now, `snippets` contains disjunct lists of commits in new -> old order. Process these in
        # reverse, one at a time until encountering a commit where we don't know the results of all
        # parents. Then put the remainder back on the stack to be further processed later until we
        # run out of snippets with commits.
        #
        # Here, the “bottom halves” of visitors get results from their parent commit(s) as well as
        # visitors run prior on the same commit, i.e. `release_number_visitor()` ->
        # `changelog_visitor()`.
        ###########################################################################################

        log.debug("=====================================")
        log.debug("Processing linear history snippets...")
        log.debug("=====================================")

        # This maps commits to their results.
        visited_results = {}

        while snippets:
            snippet = snippets.pop(0)
            if snippet:
                log.debug("Processing snippet %s", snippet[0].short_id)
            while snippet:
                # Take one commit from the tail end of the snippet and process.
                commit = snippet.pop()

                if log.isEnabledFor(logging.DEBUG):
                    log.debug("commit %s: %s", commit.short_id, commit.message.split("\n", 1)[0])

                if commit_coroutines[commit] is None:
                    # Only traverse, but don't process this commit. Ancestral commits might have to
                    # be taken into account again, so we can’t simply stop here.
                    log.debug("\tonly traverse: %s", commit.id)
                    continue

                for p in commit.parents:
                    if log.isEnabledFor(logging.DEBUG):
                        log.debug(
                            "\t%s: p in visited results: %s", p.short_id, p in visited_results
                        )
                        log.debug(
                            "\tcommit_coroutines[p] is None: %s", commit_coroutines[p] is None
                        )

                if not all(
                    p in visited_results or commit_coroutines[p] is None for p in commit.parents
                ):
                    # This commit doesn’t have all information it needs to be processed. Put it and
                    # the remainder of the snippet back to be processed later.
                    log.debug("\tputting back")
                    snippet.append(commit)
                    snippets.append(snippet)
                    break

                parent_results = [visited_results.get(p, {}) for p in commit.parents]

                # "Pipe" the (partial) result dictionaries through the second half of all visitors
                # for the commit.
                visited_results[commit] = reduce(
                    lambda commit_result, visitor: visitor.send((commit_result, parent_results)),
                    commit_coroutines[commit],
                    {"commit-id": commit.id},
                )

        return visited_results

    @staticmethod
    def _compose_release(release_number: int, verflags: dict) -> str:
        """Compose a full release string from release number and verflags.

        Handles prerelease prefix (0.), extraver, and snapinfo suffixes, and the literal text
        surrounding the ``%autorelease`` token in the Release tag.

        :param release_number: the computed release number
        :param verflags: pre-computed verflags dict from spec parsing
        :return: formatted release string (e.g. "0.3.rc1" or "5")
        """
        base = _base_release(verflags)
        prerel_str = "0." if verflags.get("prerelease") else ""
        release_with_base = release_number + base - 1
        tag_string = "".join(
            f".{t}" for t in (verflags.get("extraver"), verflags.get("snapinfo")) if t
        )
        release_prefix = verflags.get("release-prefix", "")
        release_suffix = verflags.get("release-suffix", "")
        return f"{release_prefix}{prerel_str}{release_with_base}{tag_string}{release_suffix}"

    @staticmethod
    def _newest_first(entries: Sequence[ChangelogEntry]) -> list[ChangelogEntry]:
        """Sort changelog entries chronologically, newest first, as rpmbuild requires."""
        return sorted(entries, key=lambda e: e["timestamp"], reverse=True)

    @staticmethod
    def _make_changelog_entry(commit, version: str, release: str) -> ChangelogEntry:
        """Create a ChangelogEntry from a commit and version/release strings.
        :param commit: git commit whose message should be converted to a changelog entry
        :param version: Version as specified by specfile
        :param release: Release as specified by specfile/autorelease
        :return: A changelogentry for this commit with the appropriate VR metadata
        """
        return ChangelogEntry(
            {
                "commit-id": commit.id,
                "authorblurb": f"{commit.author.name} <{commit.author.email}>",
                "timestamp": dt.datetime.fromtimestamp(commit.commit_time, dt.timezone.utc),
                "commitlog": commit.message,
                "epoch-version": version,
                "release-complete": release,
            }
        )

    def _best_tags(
        self,
        namespace: str,
        use_highest_release_tag: bool = False,
        reachable: Optional[Collection[str]] = None,
    ) -> dict[str, NVR]:
        """Map each tagged commit to its lowest (or highest) release tag.

        :param namespace: the git tag namespace to filter on
        :param use_highest_release_tag: if True, use the highest release tag per commit;
            otherwise use the lowest (first release)
        :param reachable: if set, only tagged commits with these hex shas are listed
        :return: dict mapping the hex sha of each tagged commit to its NVR
        """
        pick = max if use_highest_release_tag else min
        return {
            sha: pick(nvr_list, key=lambda n: int(n.release))
            for sha, nvr_list in self.get_tags_for_namespace(namespace).items()
            if reachable is None or sha in reachable
        }

    def _changelog_from_tags(
        self,
        namespace: str,
        use_highest_release_tag: bool = False,
        reachable: Optional[set[str]] = None,
    ) -> tuple[ChangelogEntry, ...]:
        """Generate changelog entries from git tags only, sorted by commit timestamp descending.

        Each commit produces at most one changelog entry even if it has multiple tags.
        (if multiple tags are present we use either the highest or lowest)

        :param namespace: the git tag namespace to filter on
        :param use_highest_release_tag: if True, use the highest release tag per commit;
            otherwise use the lowest (first release)
        :param reachable: if set, only tagged commits with these hex shas are listed
        :return: tuple of ChangelogEntry dicts, newest first
        """
        entries = [
            self._make_changelog_entry(self.repo.get(sha), epoch_version(nvr), nvr.release)
            for sha, nvr in self._best_tags(namespace, use_highest_release_tag, reachable).items()
        ]
        # Sort by time, not NVR, to avoid rpmbuild errors
        return tuple(self._newest_first(entries))

    def _release_from_tags(self, namespace: str, verflags: Optional[dict] = None) -> Optional[int]:
        """Compute release number from git tags in namespace and current version.

        If tags exist for the same Name and Version, returns max(Release) + 1.
        If tags exist but none match this Version (i.e. new Version), returns base.
        If no matching tags exist (i.e. new package or onboarding to tags), returns base.
        If the spec file cannot be parsed, returns None (fall through to normal walk).

        :param namespace: the git tag namespace to filter on
        :param verflags: pre-computed verflags dict (avoids redundant spec parsing)
        """
        tags = self.get_tags_for_namespace(namespace)

        if verflags is None:
            verflags = self._get_rpmverflags(self.path, name=self.name)
        if "error" in verflags:
            # Unparseable spec, quit
            return None

        base = _base_release(verflags)

        if not tags:
            # Treat no-git-tag case the same as a new package/version
            # Possibly safer bet would be fallback to default Rpmautospec behavior
            # However, the caller explicitly wanted to run in git-tag mode, so let's.
            return base

        current_version = verflags["epoch-version"]

        highest_release = max(
            (
                int(nvr.release)
                for nvr_list in tags.values()
                for nvr in nvr_list
                if epoch_version(nvr) == current_version
            ),
            default=None,
        )

        if highest_release is not None:
            return max(highest_release + 1, base)
        return base

    @staticmethod
    def _attributed_items(commit) -> list[str]:
        """The changelog items of a commit message, each followed by the author's name."""
        author = commit.author.name
        return [
            f"{item} ({author})"
            for item in ChangelogEntry.commitlog_to_changelog_items(commit.message)
        ]

    def _entry_with_messages(
        self, anchor, version: str, release: str, messages: Sequence[str]
    ) -> ChangelogEntry:
        """A changelog entry for a commit whose log is the accumulated messages."""
        entry = self._make_changelog_entry(anchor, version, release)
        entry["commitlog"] = "\n".join(messages).rstrip()
        return entry

    def _changelog_accumulated(
        self,
        namespace: str,
        head: pygit2.Commit,
        verflags: dict,
        tag_release: int,
        use_highest_release_tag: bool = False,
        *,
        start: Optional[pygit2.Commit] = None,
        reachable: Optional[set[str]] = None,
    ) -> tuple[ChangelogEntry, ...]:
        """Generate changelog by walking history and grouping commits between tags.

        Walks backwards from HEAD. Commits accumulate into the current entry
        until a tagged commit is reached, which starts a new entry.
        We repeat the process, generating changelog entries per N-V-R tags
        with all intermediate history added in.
        Commit authors are attributed as changelog entries are expanded.
        The entire commit is included so e.g. CVE, issue, etc refs are not lost.
        On unresolvable merges, jump to the next older tagged commit and
        continue the walk from there.

        This is essentially an enhanced version of the untagged history walk to
        better follow known release history.

        Note: Changelog is sorted by TIME, not N-V-R! rpmbuild errors if changelog
        is not chronological.

        :param namespace: the git tag namespace
        :param head: the HEAD commit
        :param verflags: pre-computed verflags for the spec
        :param tag_release: the computed next release number
        :param use_highest_release_tag: pick highest vs lowest release per commit
        :param start: commit to start the walk at instead of ``head`` (a tagged commit below
            commits that are handled otherwise)
        :param reachable: if set, only tagged commits with these hex shas are used. Stops the
            jump from an unresolvable merge from landing on another branch
        :return: tuple of ChangelogEntry, newest first
        """
        # Build commit -> best NVR lookup
        tag_for_commit = self._best_tags(namespace, use_highest_release_tag, reachable)

        # Sort by timestamp, not N-V-R, to avoid rpmbuild errors
        tagged_by_time = sorted(
            tag_for_commit.keys(),
            key=lambda sha: self.repo.get(sha).commit_time,
            reverse=True,
        )

        entries = []
        current_messages = []
        current_anchor = head
        current_version = verflags.get("epoch-version")
        current_release = self._compose_release(tag_release, verflags)
        visited = set()

        commit = start or head
        while commit is not None:
            sha = str(commit.id)
            visited.add(sha)

            if sha in tag_for_commit:
                # New tag, finish current entry & start a new one
                if current_messages:
                    entries.append(
                        self._entry_with_messages(
                            current_anchor, current_version, current_release, current_messages
                        )
                    )
                nvr = tag_for_commit[sha]
                current_anchor = commit
                current_version = epoch_version(nvr)
                # Grab highest or lowest V-R depending on mode
                if commit.id == head.id and use_highest_release_tag:
                    current_release = self._compose_release(tag_release, verflags)
                else:
                    current_release = nvr.release
                # Tagged commits always get their message (they were released)
                attributed = self._attributed_items(commit)
                current_messages = [attributed[0], ""]
                if len(attributed) > 1:
                    current_messages.extend(f"- {item}" for item in attributed[1:])
            else:
                # Untagged commit: honour [skip changelog] unless it's HEAD
                mc = parse_magic_comments(commit.message)
                if not mc.skip_changelog or commit.id == head.id:
                    first_message = not current_messages
                    current_messages.extend(f"- {item}" for item in self._attributed_items(commit))
                    if first_message:
                        # Force a blank line so commitlog_to_changelog_items
                        # appends correctly
                        current_messages.insert(1, "")

            commit = self._next_commit_for_walk(commit, visited, tagged_by_time)

        # Finalize last entry
        entries.append(
            self._entry_with_messages(
                current_anchor, current_version, current_release, current_messages
            )
        )

        # Sort chronologically to prevent rpmbuild errors
        return tuple(self._newest_first(entries))

    @staticmethod
    def _parent_to_follow(commit, skip: Collection[str] = ()) -> Optional[pygit2.Commit]:
        """Find the parent to follow: the only parent, or in a merge the one with the same tree.

        :param commit: the commit to find a parent of
        :param skip: hex shas of the parents that are not to be followed
        :return: the parent, or None if there is none to follow
        """
        if len(commit.parents) == 1:
            candidates = commit.parents
        else:
            # Merge done with strategy "ours" or equivalent, i.e. (at least) one parent has the
            # same content
            candidates = [parent for parent in commit.parents if commit.tree == parent.tree]
        return next((parent for parent in candidates if str(parent.id) not in skip), None)

    def _next_commit_for_walk(
        self,
        commit: pygit2.Commit,
        visited: set[str],
        tagged_by_time: list[str],
    ) -> Optional[pygit2.Commit]:
        """Find next commit walking up the git tree

        1. Single parent -> follow it
        2. Multiple parents -> find same-tree parent
        3. No same-tree parent -> jump to next older unvisited tag

        :param commit: Current commit in the walk
        :param visited: Walk history to prevent jump causing a cycle
        :param tagged_by_time: N-V-R tags sorted by time
        """
        if not commit.parents:
            # If we hit the repo root we're automatically done
            return None

        parent = self._parent_to_follow(commit, skip=visited)
        if parent is not None:
            return parent

        # We are working with divergent/detached/otherwise messy tree.
        # Instead of trying to guess the merge, just find/jump to next
        # N-V-R tag and continue from there. visited prevents loops.
        # Note: we don't filter by timestamp here because various DAG
        # manipulations (rebase, merge, cherrypicks, etc) can produce
        # non-chronological histories.
        for sha in tagged_by_time:
            if sha not in visited:
                return self.repo.get(sha)
        return None

    def _head_result(
        self, head: pygit2.Commit, verflags: dict, release_number: int
    ) -> dict[str, Any]:
        """The result for HEAD, without its changelog."""
        return {
            "commit-id": head.id,
            "verflags": verflags,
            "epoch-version": verflags.get("epoch-version"),
            "release-number": release_number,
            "release-complete": self._compose_release(release_number, verflags),
        }

    def _run_tagged(
        self,
        head: pygit2.Commit,
        git_tag_namespace: str,
        changelog_mode: str = "accumulated",
        changelog_use_highest_release_tag: bool = False,
    ) -> Optional[dict[str, Any]]:
        """Compute release and changelog using git tags.

        This is effectively an alternative run-path if tags are available.

        :param head: the HEAD commit
        :param git_tag_namespace: the namespace to filter tags on
        :param changelog_mode: "accumulated" or "tagged-only"
        :param changelog_use_highest_release_tag: pick highest vs lowest release per commit
        :return: result dict if tags matched, or None to fall through to normal walk
        """
        verflags = self._get_rpmverflags(self.path, name=self.name)
        tag_release = self._release_from_tags(git_tag_namespace, verflags=verflags)
        if tag_release is None:
            # We somehow didn't get a release number.
            # Just let run() fall back to non-tag logic.
            return None

        # `_release_from_tags()` returns the final release but everything below composes it
        # with `_compose_release()` (and process_distgit's %autorelease), which adds `base - 1`.
        tag_release -= _base_release(verflags) - 1

        head_result = self._head_result(head, verflags, tag_release)

        if changelog_mode == "tagged-only":
            historical = self._changelog_from_tags(
                git_tag_namespace,
                use_highest_release_tag=changelog_use_highest_release_tag,
            )
            head_sha = str(head.id)
            # Head may or may not be tagged, we need it either way.
            if head_sha in self.get_tags_for_namespace(git_tag_namespace):
                # If it is tagged we need to make sure we don't double-include it
                if changelog_use_highest_release_tag:
                    changelog = []
                    for e in historical:
                        if e["commit-id"] == head.id:
                            e = self._make_changelog_entry(
                                head,
                                e["epoch-version"],
                                self._compose_release(tag_release, verflags),
                            )
                        changelog.append(e)
                    changelog = tuple(changelog)
                else:
                    changelog = historical
            else:
                # Head untagged, just add it
                current_entry = self._make_changelog_entry(
                    head,
                    verflags.get("epoch-version"),
                    self._compose_release(tag_release, verflags),
                )
                changelog = (current_entry,) + historical
            head_result["changelog"] = changelog
        else:
            # Accumulate mode, no special handling needed
            head_result["changelog"] = self._changelog_accumulated(
                git_tag_namespace,
                head,
                verflags,
                tag_release,
                use_highest_release_tag=changelog_use_highest_release_tag,
            )

        return head_result

    def _find_boundary(
        self, head: pygit2.Commit, tags: dict
    ) -> tuple[set[str], Optional[pygit2.Commit]]:
        """Find the nearest and newest tagged commit below HEAD.

        :param head: the HEAD commit
        :param tags: the tagged commits, see get_tags_for_namespace()
        :return: the hex shas of the commits reachable from HEAD, and the tagged commit, None if
            there is none
        """
        reachable = set()
        boundary = None
        # Children come before their parents, newer commits first, so the first tagged commit is
        # the nearest and newest one and not an arbitrary one of several.
        for commit in self.repo.walk(
            head.id, pygit2.enums.SortMode.TOPOLOGICAL | pygit2.enums.SortMode.TIME
        ):
            sha = str(commit.id)
            reachable.add(sha)
            if boundary is None and sha in tags:
                boundary = commit
        return reachable, boundary

    def _log_no_boundary(self, changelog_mode: str, git_tag_namespace: str) -> None:
        """Say why a mixed mode walks the commit history: there is no tag below HEAD."""
        if (Path(self.repo.path) / "shallow").exists():
            log.error(
                "%s: no tag in %s below HEAD, but the repository is shallow, so a tag may be "
                "out of reach and the release number counted from the truncated history may be "
                "too low; walking the commit history",
                changelog_mode,
                git_tag_namespace,
            )
        else:
            log.warning(
                "%s: no tag in %s below HEAD, walking the commit history",
                changelog_mode,
                git_tag_namespace,
            )

    @staticmethod
    def _stop_releases(tags: dict, base: int) -> dict[str, int]:
        """The release number of the commit after each tagged commit, where the walk stops.

        That is the release after the tag, but not below the base.

        :param tags: the tagged commits, see get_tags_for_namespace()
        :param base: the base release of the spec file
        :return: dict mapping the hex sha of each tagged commit to the release counted from it
        """
        return {
            sha: max(max(int(nvr.release) for nvr in nvrs) + 1 - base, 0)
            for sha, nvrs in tags.items()
        }

    def _run_mixed(
        self,
        head: pygit2.Commit,
        git_tag_namespace: str,
        changelog_mode: str,
        changelog_use_highest_release_tag: bool = False,
    ) -> Optional[dict[str, Any]]:
        """Compute release and changelog walking the history down to the first tagged commit.

        The commits above the newest tagged ancestor get one changelog entry each and a release
        counted from that tag's release, as the history walk does. From the tagged commit down
        the mode without the ``mixed-`` prefix takes over.

        :param head: the HEAD commit
        :param git_tag_namespace: the namespace to filter tags on
        :param changelog_mode: "mixed-accumulated" or "mixed-tagged-only"
        :param changelog_use_highest_release_tag: pick highest vs lowest release per commit
        :return: result dict, or None to fall through to the normal walk
        """
        strict_mode = changelog_mode.removeprefix("mixed-")
        tags = self.get_tags_for_namespace(git_tag_namespace)

        if str(head.id) in tags:
            # HEAD is rebuilt, there is nothing above the tag to walk.
            return self._run_tagged(
                head, git_tag_namespace, strict_mode, changelog_use_highest_release_tag
            )

        verflags = self._get_rpmverflags(self.path, name=self.name)
        if "error" in verflags:
            # The parse error itself was logged while reading the spec file.
            log.warning(
                "%s: the spec file could not be parsed, walking the commit history", changelog_mode
            )
            return None

        reachable, boundary = self._find_boundary(head, tags)
        if boundary is None:
            self._log_no_boundary(changelog_mode, git_tag_namespace)
            return None

        # The walk ends at every tagged commit and continues counting from its highest tag
        with self._stopping_at(self._stop_releases(tags, _base_release(verflags))):
            walked = self._run_on_history(
                head, visitors=[self.release_number_visitor, self.changelog_visitor]
            )[head]

        if strict_mode == "tagged-only":
            tag_entries = self._changelog_from_tags(
                git_tag_namespace,
                use_highest_release_tag=changelog_use_highest_release_tag,
                reachable=reachable,
            )
        else:
            tag_entries = self._changelog_accumulated(
                git_tag_namespace,
                head,
                verflags,
                walked["release-number"],
                use_highest_release_tag=changelog_use_highest_release_tag,
                start=boundary,
                reachable=reachable,
            )

        # Sort chronologically to prevent rpmbuild errors
        changelog = self._newest_first((*walked.get("changelog", ()), *tag_entries))

        return {
            **self._head_result(head, verflags, walked["release-number"]),
            "changelog": tuple(changelog),
        }

    def run(
        self,
        head: Optional[Union[str, pygit2.Commit]] = None,
        *,
        visitors: Sequence = (),
        all_results: bool = False,
        git_tag_namespace: Optional[str] = None,
        changelog_mode: Optional[str] = None,
        changelog_use_highest_release_tag: Optional[bool] = None,
    ) -> Union[dict[str, Any], dict[pygit2.Commit, dict[str, Any]]]:
        """Process a package repository including a changed worktree.

        :param git_tag_namespace: if set, derive the release and changelog from git tags in this
            namespace
        :param changelog_mode: one of CHANGELOG_MODES, None for the default
            (accumulated with a git tag namespace, walk otherwise)
        :param changelog_use_highest_release_tag: pick highest vs lowest release per commit
        """
        changelog_mode, changelog_use_highest_release_tag = self._resolve_changelog_options(
            self._get_changelog_flags(),
            git_tag_namespace,
            changelog_mode,
            changelog_use_highest_release_tag,
        )

        # whether or not the worktree differs and this needs to be reflected in the result(s)
        reflect_worktree = False

        if self.repo:
            seed_info = None
            if not head:
                head = self.repo[self.repo.head.target]
                diff_to_head = self.repo.diff(head)
                reflect_worktree = diff_to_head.stats.files_changed > 0
                if (
                    reflect_worktree
                    and not (self.specfile.parent / "changelog").exists()
                    and "changelog" in head.tree
                ):
                    seed_info = {"changelog_removed": True}
            elif isinstance(head, str):
                head = self.repo[head]

            if changelog_mode in TAG_CHANGELOG_MODES:
                # If git tags are available use them instead of naive-reading the repo
                # We *do* actually support dirty worktree since make sources target may
                # have done some weird manipulation (e.g. multi-version unified git repos)
                # Note: this does mean such packages *must* use git tags.
                tagged_run = (
                    self._run_mixed if changelog_mode.startswith("mixed-") else self._run_tagged
                )
                head_result = tagged_run(
                    head,
                    git_tag_namespace,
                    changelog_mode=changelog_mode,
                    changelog_use_highest_release_tag=changelog_use_highest_release_tag,
                )
                if head_result is not None:
                    if all_results:
                        return {head: head_result}
                    return head_result

            visited_results = self._run_on_history(head, visitors=visitors, seed_info=seed_info)
            head_result = visited_results[head]
        else:
            reflect_worktree = True
            visited_results = {}
            head_result = {}

        if reflect_worktree:
            # Not a git repository, or the git worktree isn't clean.
            worktree_result = {}

            verflags = self._get_rpmverflags(self.path, name=self.name)
            if "error" in verflags:
                # cringe, but what can you do?
                verflags |= {
                    "epoch-version": None,
                    "prerelease": False,
                    "extraver": None,
                    "snapinfo": None,
                    "base": 1,
                    "release-prefix": "",
                    "release-suffix": "",
                }

            # Mimic the bottom half of release_number_visitor
            worktree_result["verflags"] = verflags
            worktree_result["epoch-version"] = epoch_version = verflags["epoch-version"]
            if head_result and epoch_version == head_result["epoch-version"]:
                release_number = head_result["release-number"] + 1
            else:
                release_number = 1
            worktree_result["release-number"] = release_number

            worktree_result["release-complete"] = release_complete = self._compose_release(
                release_number, verflags
            )

            # Mimic the bottom half of the changelog visitor for a generic entry
            if not self.specfile.exists():
                changelog = ()
            else:
                previous_changelog = head_result.get("changelog", ())

                try:
                    signature = self.repo.default_signature
                    authorblurb = f"{signature.name} <{signature.email}>"
                except AttributeError:
                    # self.repo == None -> no git repo
                    authorblurb = self._get_rpm_packager()
                except KeyError:
                    authorblurb = "Unknown User <please-configure-git-user@example.com>"

                changelog_entry = ChangelogEntry(
                    {
                        "commit-id": None,
                        "authorblurb": authorblurb,
                        "timestamp": dt.datetime.now(dt.timezone.utc),
                        "commitlog": "Uncommitted changes",
                        "epoch-version": epoch_version,
                        "release-complete": release_complete,
                    }
                )

                changelog = (changelog_entry,) + previous_changelog

            worktree_result["changelog"] = changelog
            visited_results[None] = worktree_result

        # Sort results chronologically to prevent rpmbuild errors
        result = worktree_result if reflect_worktree else head_result
        if "changelog" in result:
            result["changelog"] = tuple(self._newest_first(result["changelog"]))

        if all_results:
            return visited_results
        elif reflect_worktree:
            return worktree_result
        else:
            return head_result
